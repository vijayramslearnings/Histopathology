"""Unit tests for context-aware findings chatbot."""

from __future__ import annotations

from chatbot.assistant import FindingsChatbot
from chatbot.context import session_manager
from chatbot.prompts import DeterministicIntentEngine


def get_mock_findings():
    return {
        "prediction": {
            "cancer_type": "BRCA",
            "confidence": 0.914,
            "class_probabilities": {"BRCA": 0.914, "LUAD": 0.032, "GBM": 0.028, "Other": 0.026},
        },
        "subtype": {
            "label": "Invasive_Ductal",
            "confidence": 0.826,
            "probabilities": {"Invasive_Ductal": 0.826, "Lobular": 0.174},
        },
        "scale_attention": {"5x": 0.18, "10x": 0.32, "20x": 0.50},
        "dominant_scale": "20x",
        "important_regions": [
            {
                "region_id": 1,
                "scale": "20x",
                "attention_score": 0.94,
                "coordinates": {"x": 420, "y": 280, "width": 56, "height": 56},
            }
        ],
        "faithfulness": {"deletion_auc": 0.42, "insertion_auc": 0.78},
        "stability": {"ssim": 0.87, "correlation": 0.89, "prediction_stability": 1.0},
        "uncertainty": {"entropy": 0.45, "top2_confidence": 0.032, "is_low_confidence": False},
        "research_disclaimer": "This output is generated by an experimental AI research model and is not a clinical diagnosis.",
    }


def test_deterministic_intent_engine():
    findings = get_mock_findings()
    
    ans1 = DeterministicIntentEngine.answer("What did the model predict?", findings)
    assert "BRCA" in ans1 and "91.4%" in ans1

    ans2 = DeterministicIntentEngine.answer("Why did it predict BRCA?", findings)
    assert "highest probability" in ans2 or "BRCA" in ans2

    ans3 = DeterministicIntentEngine.answer("Does this image prove that I have cancer?", findings)
    assert "cannot establish a medical diagnosis" in ans3

    ans4 = DeterministicIntentEngine.answer("Which scale was most important?", findings)
    assert "20x" in ans4


def test_findings_chatbot_asking():
    bot = FindingsChatbot(api_key=None)  # Force fallback engine mode
    findings = get_mock_findings()

    res = bot.ask(
        message="What did the model predict?",
        analysis_result={"structured_findings": findings},
        session_id="test_session_1",
    )

    assert "answer" in res
    assert "BRCA" in res["answer"]
    assert "research_disclaimer" in res

    # Follow-up without re-passing analysis_result (session context test)
    res2 = bot.ask(
        message="Which scale was most important?",
        session_id="test_session_1",
    )
    assert "20x" in res2["answer"]
