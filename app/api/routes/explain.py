"""API Route for Explainable AI (XAI) analysis."""

from __future__ import annotations

from pathlib import Path
from fastapi import APIRouter, HTTPException, status

from app.core.exceptions import XAIError
from app.schemas.explain import ExplainRequest, ExplainResponse
from prediction.inference import predict_image
from xai.explain import XAIEngine
from .predict import get_model_and_meta

router = APIRouter(tags=["Explainable AI"])


@router.post("/explain", response_model=ExplainResponse, summary="Generate XAI Explanations & Quantitative Metrics")
async def explain_endpoint(payload: ExplainRequest) -> ExplainResponse:
    """Generate Grad-CAM, patch and scale attention, faithfulness, stability, and findings JSON."""
    if not Path(payload.image_path).exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Image file not found at path: {payload.image_path}",
        )
    try:
        model, cancer_classes, subtype_classes, image_size, model_name, scale_fractions, device = get_model_and_meta(
            payload.checkpoint_path
        )
        
        # 1. Run prediction to get model logits & weights
        pred_result = predict_image(
            model=model,
            image_path=payload.image_path,
            cancer_classes=cancer_classes,
            subtype_classes=subtype_classes,
            image_size=image_size,
            model_name=model_name,
            device=device,
            scale_fractions=scale_fractions,
            organ_type=payload.organ_type,
        )

        # 2. Run XAI Engine
        engine = XAIEngine(
            model=model,
            cancer_classes=cancer_classes,
            subtype_classes=subtype_classes,
            image_size=image_size,
            scale_fractions=scale_fractions,
            device=device,
        )

        xai_result = engine.explain(
            image_path=payload.image_path,
            prediction_result=pred_result,
            target_class_index=payload.target_class_index,
            evaluate_eval_metrics=payload.evaluate_eval_metrics,
        )

        return ExplainResponse(
            research_disclaimer="This output is generated by an experimental AI research model and is not a clinical diagnosis.",
            structured_findings=xai_result["structured_findings"],
            findings_summary=xai_result["findings_summary"],
            xai_combination=xai_result["xai_combination"],
        )
    except Exception as e:
        raise XAIError(f"XAI explanation generation failed: {str(e)}")
