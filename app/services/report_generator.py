"""Automated PDF Research Report Generator using ReportLab."""

from __future__ import annotations

import io
from pathlib import Path
from typing import Any, Dict, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import (
    HRFlowable,
    Image as RLImage,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)


def generate_pdf_report(
    analysis_result: Dict[str, Any],
    output_path: Optional[str | Path] = None,
) -> bytes:
    """Generate a computational pathology PDF research report from analysis results."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        output_path if output_path else buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
    )
    disclaimer_style = ParagraphStyle(
        "DisclaimerText",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#991b1b"),
    )
    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
    )
    bold_style = ParagraphStyle(
        "ReportBold",
        parent=body_style,
        fontName="Helvetica-Bold",
    )

    elements = []

    # 1. Header Title
    elements.append(Paragraph("Explainable Computational Pathology Report", title_style))
    elements.append(Paragraph("Multi-Scale Attention & Multiple Instance Learning Framework", body_style))
    elements.append(Spacer(1, 10))

    # 2. Research Disclaimer Banner
    disclaimer_html = (
        "<b>RESEARCH USE ONLY DISCLAIMER:</b> This software report is generated by an experimental "
        "computational pathology research model. It is <b>NOT</b> a clinical diagnostic system and "
        "must <b>NEVER</b> be used for clinical decision-making or patient diagnosis."
    )
    disc_table = Table(
        [[Paragraph(disclaimer_html, disclaimer_style)]],
        colWidths=[540],
    )
    disc_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fef2f2")),
        ("BORDER", (0, 0), (-1, -1), 1, colors.HexColor("#fecaca")),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(disc_table)
    elements.append(Spacer(1, 15))

    # 3. Sample Metadata Table
    cancer_info = analysis_result.get("cancer", {})
    subtype_info = analysis_result.get("subtype", {})
    unc_info = analysis_result.get("uncertainty", {})

    meta_data = [
        [
            Paragraph("<b>Sample Image:</b>", body_style),
            Paragraph(str(analysis_result.get("image_path", "N/A")), body_style),
            Paragraph("<b>Organ Origin:</b>", body_style),
            Paragraph(str(analysis_result.get("organ_type", "Auto")), body_style),
        ],
        [
            Paragraph("<b>Predicted Cancer:</b>", body_style),
            Paragraph(f"<b>{cancer_info.get('label', 'N/A')}</b>", body_style),
            Paragraph("<b>Confidence:</b>", body_style),
            Paragraph(f"{cancer_info.get('confidence', 0.0):.2%}", body_style),
        ],
        [
            Paragraph("<b>Subtype Classification:</b>", body_style),
            Paragraph(f"{subtype_info.get('label', 'N/A')}", body_style),
            Paragraph("<b>Subtype Confidence:</b>", body_style),
            Paragraph(f"{subtype_info.get('confidence', 0.0):.2%}", body_style),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[130, 140, 130, 140])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 15))

    # 4. Probabilities Breakdown Table
    elements.append(Paragraph("<b>Primary Cancer Class Probabilities</b>", ParagraphStyle("H2", parent=styles["Heading2"], fontSize=12, leading=15)))
    elements.append(Spacer(1, 5))

    probs_data = [["Cancer Label", "Probability", "Confidence Status"]]
    probs = cancer_info.get("probabilities", {})
    for clabel, cprob in probs.items():
        is_top = clabel == cancer_info.get("label")
        probs_data.append([
            clabel,
            f"{cprob:.2%}",
            "Primary Prediction" if is_top else "Alternative",
        ])
    
    probs_table = Table(probs_data, colWidths=[180, 180, 180])
    probs_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(probs_table)
    elements.append(Spacer(1, 15))

    # 5. Multi-Scale Attention Distribution
    elements.append(Paragraph("<b>Multi-Scale & Spatial Attention Distribution</b>", ParagraphStyle("H2", parent=styles["Heading2"], fontSize=12, leading=15)))
    elements.append(Spacer(1, 5))

    scale_att = analysis_result.get("scale_attention", {})
    scale_data = [
        ["Scale Level", "Relative Scale Fraction", "Attention Weight"],
        ["Low Scale", "0.55x Context", f"{scale_att.get('low', 0.33):.2%}"],
        ["Medium Scale", "0.75x Context", f"{scale_att.get('medium', 0.33):.2%}"],
        ["High Scale", "1.00x Full Detail", f"{scale_att.get('high', 0.34):.2%}"],
    ]
    scale_table = Table(scale_data, colWidths=[180, 180, 180])
    scale_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0284c7")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(scale_table)
    elements.append(Spacer(1, 15))

    # 6. Uncertainty & Quality Summary
    elements.append(Paragraph("<b>Uncertainty & Abstention Metrics</b>", ParagraphStyle("H2", parent=styles["Heading2"], fontSize=12, leading=15)))
    elements.append(Spacer(1, 5))
    unc_text = (
        f"<b>Shannon Entropy:</b> {unc_info.get('entropy', 0.0):.4f} bits<br/>"
        f"<b>Out-Of-Distribution Flag:</b> {unc_info.get('ood', False)}<br/>"
        f"<b>Abstention Warning:</b> {unc_info.get('message', 'Normal in-distribution classification.')}"
    )
    elements.append(Paragraph(unc_text, body_style))

    # Build Document
    doc.build(elements)

    if output_path:
        return Path(output_path).read_bytes()
    return buffer.getvalue()
