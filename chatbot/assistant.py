"""Context-aware Findings Chatbot with Google GenAI / Gemini integration and offline fallback."""

from __future__ import annotations

import json
import os
from typing import Any, Dict, Optional

from .context import session_manager
from .prompts import SYSTEM_PROMPT, DeterministicIntentEngine


class FindingsChatbot:
    """Chatbot assistant providing context-aware explanations of histopathology model outputs."""

    def __init__(self, api_key: Optional[str] = None) -> None:
        self.api_key = api_key or os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
        self._client: Optional[Any] = None
        
        if self.api_key:
            try:
                from google import genai
                self._client = genai.Client(api_key=self.api_key)
            except Exception:
                self._client = None

    def ask(
        self,
        message: str,
        analysis_result: Optional[Dict[str, Any]] = None,
        session_id: str = "default_session",
    ) -> Dict[str, Any]:
        """Process user question against model findings and return factual explanation."""
        
        # 1. Update or retrieve session context
        if analysis_result is not None:
            session_manager.set_analysis_result(session_id, analysis_result)
        else:
            analysis_result = session_manager.get_analysis_result(session_id)

        if not analysis_result:
            return {
                "answer": "That information is not available from the current model output. Please run an analysis first.",
                "session_id": session_id,
                "research_disclaimer": "This output is generated by an experimental AI research model and is not a clinical diagnosis.",
            }

        # Extract structured findings if present, else build standard dict
        findings = analysis_result.get("structured_findings", analysis_result)

        # Record user message in history
        session_manager.add_message(session_id, "user", message)

        answer: str = ""

        # 2. Attempt LLM generation if API client is initialized
        if self._client is not None:
            try:
                # Format JSON context for prompt
                json_context = json.dumps(findings, indent=2)
                full_prompt = (
                    f"SYSTEM INSTRUCTIONS:\n{SYSTEM_PROMPT}\n\n"
                    f"CURRENT MODEL ANALYSIS FINDINGS (JSON):\n{json_context}\n\n"
                    f"USER QUESTION: {message}\n\n"
                    "Provide a direct, factual explanation strictly based on the JSON findings above:"
                )
                response = self._client.models.generate_content(
                    model="gemini-2.5-flash",
                    contents=full_prompt,
                )
                answer = response.text.strip() if response and response.text else ""
            except Exception:
                # Fallback to deterministic intent engine if LLM fails
                answer = ""

        # 3. Use deterministic engine fallback if answer is empty or LLM not available
        if not answer:
            answer = DeterministicIntentEngine.answer(message, findings)

        # Record assistant answer in history
        session_manager.add_message(session_id, "assistant", answer)

        return {
            "answer": answer,
            "session_id": session_id,
            "research_disclaimer": "This output is generated by an experimental AI research model and is not a clinical diagnosis.",
        }
