"""Structured Findings JSON builder and deterministic natural language Findings Generator."""

from __future__ import annotations

from typing import Any, Dict, List, Optional


def build_structured_findings(
    prediction_result: Dict[str, Any],
    scale_info: Dict[str, Any],
    top_regions: List[Dict[str, Any]],
    gradcam_info: Dict[str, Any],
    patch_info: Dict[str, Any],
    faithfulness_info: Dict[str, Any],
    stability_info: Dict[str, Any],
) -> Dict[str, Any]:
    """Construct the standardized JSON findings object conforming to Section 12 specification."""
    
    cancer_type = prediction_result.get("cancer_type", "Unknown")
    confidence = prediction_result.get("cancer_confidence", 0.0)
    class_probs = prediction_result.get("cancer_probabilities", {})
    
    organ_type = prediction_result.get("organ_type", "Auto")
    has_cancer = prediction_result.get("has_cancer", True)
    cancer_status = prediction_result.get("cancer_status", f"Cancer Detected ({cancer_type})")

    subtype = prediction_result.get("subtype", {
        "label": None,
        "confidence": None,
        "probabilities": {},
        "message": "Subtype prediction is not available for this sample."
    })

    return {
        "organ_type": organ_type,
        "has_cancer": has_cancer,
        "cancer_status": cancer_status,
        "prediction": {
            "cancer_type": cancer_type,
            "confidence": round(float(confidence), 4),
            "class_probabilities": {k: round(float(v), 4) for k, v in class_probs.items()},
        },
        "subtype": subtype,
        "scale_attention": scale_info.get("scale_attention", {}),
        "dominant_scale": scale_info.get("dominant_scale", "unknown"),
        "important_regions": top_regions,
        "gradcam": {
            "heatmap_path": gradcam_info.get("heatmap_path", ""),
            "overlay_path": gradcam_info.get("overlay_path", ""),
        },
        "patch_attention": {
            "top_5": patch_info.get("top_5", []),
            "top_10": patch_info.get("top_10", []),
            "least_5": patch_info.get("least_5", []),
            "visualization_path": patch_info.get("visualization_path", ""),
        },
        "faithfulness": {
            "deletion_auc": faithfulness_info.get("deletion_auc"),
            "insertion_auc": faithfulness_info.get("insertion_auc"),
            "deletion_curve": faithfulness_info.get("deletion_curve", []),
            "insertion_curve": faithfulness_info.get("insertion_curve", []),
        },
        "stability": {
            "prediction_stability": stability_info.get("prediction_stability"),
            "ssim": stability_info.get("ssim"),
            "correlation": stability_info.get("correlation"),
            "iou": stability_info.get("region_iou"),
        },
        "uncertainty": {
            "entropy": round(float(prediction_result.get("entropy", 0.0)), 4),
            "top2_confidence": round(float(prediction_result.get("top2_confidence", 0.0)), 4),
            "is_low_confidence": bool(prediction_result.get("is_low_confidence", False)),
            "warning": prediction_result.get("confidence_warning"),
        },
        "research_disclaimer": (
            "This output is generated by an experimental AI research model and is not a clinical diagnosis."
        ),
    }


def generate_findings_summary(findings: Dict[str, Any]) -> str:
    """Generate concise, deterministic research summary text strictly adhering to objective wording rules."""
    organ_type = findings.get("organ_type", "Auto")
    cancer_status = findings.get("cancer_status", "Cancer Analysis")
    pred = findings["prediction"]
    cancer_type = pred["cancer_type"]
    confidence_pct = round(pred["confidence"] * 100.0, 1)

    subtype_info = findings.get("subtype", {})
    subtype_label = subtype_info.get("label")
    subtype_conf = subtype_info.get("confidence")

    scale_att = findings.get("scale_attention", {})
    dom_scale = findings.get("dominant_scale", "dominant scale")
    dom_pct = round(scale_att.get(dom_scale, 0.0) * 100.0, 1) if dom_scale in scale_att else None

    important_regions = findings.get("important_regions", [])
    highest_patch_score = (
        important_regions[0]["attention_score"] if important_regions else None
    )

    lines: List[str] = []
    lines.append(f"Organ specified: {organ_type}. Model assessment: {cancer_status} ({confidence_pct}% confidence).")

    if subtype_label:
        sub_conf_pct = round(subtype_conf * 100.0, 1) if subtype_conf else 0.0
        lines.append(f"Predicted Histopathological Subtype: {subtype_label} with {sub_conf_pct}% confidence.")

    if dom_pct is not None:
        lines.append(f"The model assigned the highest scale attention to the {dom_scale} representation ({dom_pct}%).")

    if highest_patch_score is not None:
        lines.append(
            f"Several image regions received relatively high patch-attention scores, with the highest attention region scoring {highest_patch_score:.2f}."
        )

    lines.append(f"The Grad-CAM visualization shows the image areas that contributed most strongly to the {cancer_type} prediction.")

    if findings.get("uncertainty", {}).get("is_low_confidence"):
        lines.append("Notice: Low-confidence model prediction. Review the image and model explanation carefully.")

    lines.append("These outputs describe model behavior and should not be interpreted as a clinical diagnosis.")

    return "\n\n".join(lines)
